SUPPORTED_LANGUAGES = ["en", "sv", "ru"]

DEFAULT_LANGUAGE = "en"


def gettext(key, lang="en", **kwargs):
    """Get translated string by key with optional formatting."""
    strings = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANGUAGE])
    text = strings.get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError) as exc:
            text = f"{text} [format error: {exc}]"
    return text
